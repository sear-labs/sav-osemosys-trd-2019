#!/usr/bin/env python
"""Regenerate model/Results_Scenario.gms from the shipped Results_Baseline.gms.

    python scripts/derive_results_writer.py

The scenario driver needs the 2018 results writer with one change: the output path
comes from a command-line parameter instead of being hardcoded. Deriving it rather
than maintaining a hand-edited third copy means the only way the three can disagree
is a deliberate edit, which scripts/check_writers.py then catches.
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC = ROOT / "model" / "Results_Baseline.gms"
DST = ROOT / "model" / "Results_Scenario.gms"

HEADER = """* Results writer for the scenario driver.
*
* GENERATED by scripts/derive_results_writer.py from Results_Baseline.gms - do not
* edit. Identical to the shipped Results_Baseline.gms / Results_CO2_Policy.gms apart
* from the put-file name and its target, which come from %RESULTSFILE%. Those two
* shipped files are the 2018 artifact and are left untouched;
* scripts/check_writers.py asserts all three still agree section for section.

"""

OLD_TARGET = "/OSeMOSYS_ATX_Baseline_Results.csv/"
NEW_TARGET = "/'%RESULTSFILE%'/"


def main() -> int:
    src = SRC.read_text(errors="replace")
    if OLD_TARGET not in src:
        print(f"error: {SRC.name} no longer contains {OLD_TARGET}", file=sys.stderr)
        return 1

    body = src.replace("Results_Baseline", "ResultsFile").replace(OLD_TARGET, NEW_TARGET)
    if "Results_Baseline" in body or "%RESULTSFILE%" not in body:
        print("error: substitution left the writer in an inconsistent state", file=sys.stderr)
        return 1

    DST.write_text(HEADER + body, newline="\n")
    print(f"wrote {DST.relative_to(ROOT)} ({len(body.splitlines())} lines from {SRC.name})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
